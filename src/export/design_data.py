"""
Export what the Design tab needs as plain-script data files.

    python -m src.export.design_data

web/data/kf_table.js     the relativistic-factor table (models/kf_table.json)
web/data/design_meta.js  calibration, the three accuracy numbers, presets
web/data/pareto.js       precomputed fronts + knees + G3 verification, used when
                         the API is asleep or unreachable

Every number in design_meta is read from a file this repo computed, or computed
here from the dataset; the source is written next to it.
"""

import json
import os

import numpy as np
import pandas as pd

from ..ann import dataset as ds
from ..physics import closure, kf

ROOT = ds.repo_root()
WEB = os.path.join(ROOT, "web", "data")
HEADER = ("/* GENERATED by src/export/design_data.py -- do not edit.\n"
          "   Plain script, because browsers block fetch() on file:// URLs. */\n"
          "window.EGUN_DATA = window.EGUN_DATA || {};\n")


def _write(name, key, obj):
    with open(os.path.join(WEB, name), "w", encoding="utf-8") as f:
        f.write(HEADER + f"window.EGUN_DATA.{key} = " + json.dumps(obj) + ";\n")


def vaughan_floor():
    """Exact-solver theta_T (via the G1-verified emulator) against all 30 measured guns."""
    lit = ds.literature_only(ds.load())
    r = closure.from_pcr(lit.perveance_uperv, lit.rw_mm, lit.C)
    m = lit.theta_cone_deg.to_numpy(float)
    e = np.abs(r["thetaT"] - m) / m * 100
    p = np.abs(lit.theta_iterative_deg - lit.theta_cone_deg) / lit.theta_cone_deg * 100
    return {"exact_solver_mre_pct_30": float(e.mean()),
            "paper_iterative_column_mre_pct_30": float(p.mean()), "n": int(len(lit))}


def meta():
    with open(os.path.join(ROOT, "reports", "gates", "G1.json"), encoding="utf-8") as f:
        g1 = json.load(f)
    with open(os.path.join(ROOT, "reports", "synthetic_roles.json"), encoding="utf-8") as f:
        sr = json.load(f)
    return {
        "calibrator": sr["closure_calibrator_scalar"],
        "calibration_band_pct": sr["band_scalar_pct_p90_loo"],
        "calibration_envelope": sr["calibration_envelope"],
        "emulator_vs_exact": {
            "theta_mean_rel": g1["worst_theta_mean_rel"],
            "theta_max_rel": max(g1["errors"]["theta"]["max"], g1["errors"]["thetaT"]["max"]),
            "length_max_rel": max(v["max"] for k, v in g1["errors"].items()
                                  if k.endswith("_mm")),
            "n": g1["n_feasible_both"], "source": "reports/gates/G1.json"},
        "vaughan_floor": {**vaughan_floor(), "source": "computed from dataset_master.csv"},
        "test7": {**sr["test_7_guns_mre_pct"], "source": "reports/synthetic_roles.json"},
        "presets": [
            {"name": "Shin et al. 35 GHz EIK", "V": 14000, "I": 0.5, "rw_mm": 0.2255, "Jc": 5},
            {"name": "CEERI 8 MW klystron (Kant & Nagaraju 2021)", "V": 150000, "I": 120,
             "rw_mm": 9.8, "Jc": 5},
            {"name": "Low-convergence 20 kV gun", "V": 20000, "I": 1, "rw_mm": 0.5, "Jc": 5},
        ],
        "api_url": "",
    }


def fronts():
    out = {}
    for name in ("shin_eik", "ceeri_klystron"):
        d = os.path.join(ROOT, "reports", "moo", name)
        if not os.path.exists(os.path.join(d, "pareto.csv")):
            continue
        with open(os.path.join(d, "knee.json"), encoding="utf-8") as f:
            knee = json.load(f)
        with open(os.path.join(d, "run.json"), encoding="utf-8") as f:
            run = json.load(f)
        ver = pd.read_csv(os.path.join(d, "verify.csv"))
        out[name] = {
            "title": run["study"]["title"], "objectives": run["study"]["objectives"],
            "evaluations": run["evaluations"],
            "pareto": pd.read_csv(os.path.join(d, "pareto.csv")).to_dict(orient="records"),
            "knee": knee,
            "verify": {"n": int(len(ver)), "max_rel_err": float(np.nanmax(ver.max_err)),
                       "all_ok": bool(ver.ok.all())},
        }
    return out


def main():
    t = dict(kf.load_table())
    t["kf"] = t["kf"].tolist()
    _write("kf_table.js", "kfTable", t)
    _write("design_meta.js", "designMeta", meta())
    _write("pareto.js", "pareto", fronts())
    print("wrote web/data/kf_table.js, design_meta.js, pareto.js")


if __name__ == "__main__":
    main()
